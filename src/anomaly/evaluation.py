"""Evaluation metrics and benchmark runner for anomaly detection models."""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple
import numpy as np
import pandas as pd
from sklearn.metrics import precision_recall_fscore_support, roc_auc_score, confusion_matrix

from src.anomaly.detector import AnomalyReport


class AnomalyEvaluator:
    """Evaluates anomaly detection performance rigorously, supporting both labeled benchmarks and unsupervised profiles."""

    @staticmethod
    def evaluate_with_ground_truth(
        reports: List[AnomalyReport],
        ground_truth_labels: np.ndarray,
        fault_onset_index: Optional[int] = None
    ) -> Dict[str, Any]:
        """Compute standard supervised classification and detection latency metrics.
        
        Args:
            reports: List of AnomalyReport generated by a detector
            ground_truth_labels: Binary array (1 = Anomaly, 0 = Nominal)
            fault_onset_index: Index where true fault was injected
        """
        y_true = np.asarray(ground_truth_labels, dtype=int)
        y_pred = np.array([1 if r.is_anomaly else 0 for r in reports], dtype=int)
        scores = np.array([r.anomaly_score for r in reports], dtype=float)

        if len(y_true) != len(y_pred):
            raise ValueError("Length of ground truth labels must match reports")

        # Precision, recall, f1
        prec, rec, f1, _ = precision_recall_fscore_support(y_true, y_pred, average="binary", zero_division=0)
        
        # Confusion matrix: TN, FP, FN, TP
        cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
        tn, fp, fn, tp = cm.ravel() if cm.size == 4 else (0, 0, 0, 0)
        
        # False alarm rate (FP / (FP + TN))
        far = fp / (fp + tn) if (fp + tn) > 0 else 0.0

        # AUROC (handle single-class edge case)
        try:
            auroc = float(roc_auc_score(y_true, scores)) if len(np.unique(y_true)) > 1 else None
        except Exception:
            auroc = None

        # Detection Latency (timesteps after fault onset before first detection)
        detection_latency_steps = None
        if fault_onset_index is not None and fault_onset_index < len(y_pred):
            post_onset_preds = y_pred[fault_onset_index:]
            hits = np.where(post_onset_preds == 1)[0]
            if len(hits) > 0:
                detection_latency_steps = int(hits[0])

        return {
            "has_ground_truth": True,
            "total_samples": len(y_true),
            "true_anomalies_count": int(np.sum(y_true)),
            "detected_anomalies_count": int(np.sum(y_pred)),
            "precision": float(prec),
            "recall": float(rec),
            "f1_score": float(f1),
            "false_alarm_rate": float(far),
            "roc_auc": auroc,
            "confusion_matrix": {"TN": int(tn), "FP": int(fp), "FN": int(fn), "TP": int(tp)},
            "detection_latency_steps": detection_latency_steps
        }

    @staticmethod
    def profile_unlabeled_series(reports: List[AnomalyReport]) -> Dict[str, Any]:
        """Compute statistical profile of detector behavior when ground-truth labels are unavailable."""
        scores = np.array([r.anomaly_score for r in reports], dtype=float)
        triggers = np.array([1 if r.is_anomaly else 0 for r in reports], dtype=int)

        # Count affected signal occurrences
        signal_counts: Dict[str, int] = {}
        for r in reports:
            for s in r.affected_signals:
                signal_counts[s] = signal_counts.get(s, 0) + 1

        return {
            "has_ground_truth": False,
            "total_samples": len(reports),
            "trigger_rate": float(np.mean(triggers)),
            "score_mean": float(np.mean(scores)),
            "score_std": float(np.std(scores)),
            "score_p50": float(np.percentile(scores, 50)),
            "score_p95": float(np.percentile(scores, 95)),
            "score_max": float(np.max(scores)),
            "signal_attribution_counts": signal_counts,
            "note": "Evaluated without ground-truth labels using distribution metrics. No fabricated accuracy claims."
        }
